export function demoSafetyQuestions(): SafetyQuestion[] {
  return demoPrompts.map(([prompt, answer, explanation], index) => {
    const options = ['无需确认，直接处理', '只参考旧截图即可', '由其他成员替自己确认'];
    const rightIndex = index % 4;
    options.splice(rightIndex, 0, answer);
    return { id: `demo-${String(index + 1).padStart(2, '0')}`, prompt, options, rightIndex, explanation };
  });
}
export function seedLearningDemo(snapshot: StoreSnapshot): StoreSnapshot {
  const id = key('learning-bank', 'oradv');
  if (snapshot.learning_catalog?.[id]) return snapshot;
  const bank: LearningBank = { id, clubId: 'oradv', title: '演示知识练习', questions: demoSafetyQuestions(), published: true, fixtureOnly: true, revision: 1 };
  return { ...snapshot, learning_catalog: { ...snapshot.learning_catalog, [id]: bank } };
}
